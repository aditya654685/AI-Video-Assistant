SUPPORTED_TYPES = ["mp4", "mkv", "mov", "avi", "webm", "mp3", "wav", "m4a", "aac", "flac", "ogg"]
YOUTUBE_RE = re.compile(r"^(https?://)?(www\.|m\.)?(youtube\.com|youtu\.be)/.+", re.IGNORECASE)


def to_items(content) -> list[str]:
    """Normalise extractor output (list, dict, or text block) into a list of strings."""
    if content is None:
        return []
    if isinstance(content, dict):
        return [f"**{k}:** {v}" for k, v in content.items()]
    if isinstance(content, (list, tuple)):
        return [str(x).strip() for x in content if str(x).strip()]
    lines = [ln.strip() for ln in str(content).splitlines() if ln.strip()]
    bullet = re.compile(r"^([-*•]|\d+[.)])\s+")
    if lines and sum(bool(bullet.match(ln)) for ln in lines) >= max(1, len(lines) // 2):
        return [bullet.sub("", ln) for ln in lines if bullet.match(ln)]
    return [str(content).strip()]


def render_cards(content, kind: str, empty_msg: str):
    items = to_items(content)
    if not items or items == ["None"] or items == [""]:
        st.info(empty_msg)
        return
    for item in items:
        st.markdown(f'<div class="item-card {kind}">{item}</div>', unsafe_allow_html=True)


def as_markdown_list(content) -> str:
    items = to_items(content)
    return "\n".join(f"- {i}" for i in items) if items else "_None_"


def build_report(result: dict) -> str:
    return f"""# {result['title']}

_Generated by AI Video Assistant on {datetime.now():%d %b %Y, %H:%M}_

## Summary
{result['summary']}

## Action Items
{as_markdown_list(result['action_items'])}

## Key Decisions
{as_markdown_list(result['key_decisions'])}

## Open Questions
{as_markdown_list(result['open_questions'])}

---

## Full Transcript
{result['transcript']}
"""


def save_upload(uploaded_file) -> str:
    suffix = os.path.splitext(uploaded_file.name)[1] or ".mp4"
    tmp = tempfile.NamedTemporaryFile(delete=False, suffix=suffix)
    tmp.write(uploaded_file.getbuffer())
    tmp.close()
    return tmp.name


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "meeting"


def run_pipeline_with_progress(source: str, language: str) -> dict:
    """Same steps as main.run_pipeline, but with live progress in the UI."""
    steps = [
        ("🎧 Extracting & chunking audio", None),
        ("📝 Transcribing", None),
        ("📌 Generating title", None),
        ("📋 Summarising", None),
        ("✅ Extracting action items", None),
        ("🔑 Extracting key decisions", None),
        ("❓ Extracting open questions", None),
        ("🧠 Building chat index (RAG)", None),
    ]
    total = len(steps)
    progress = st.progress(0.0, text="Starting…")
    result = {}

    with st.status("Processing your video…", expanded=True) as status:

        def step(i: int, label: str, fn, *args):
            progress.progress(i / total, text=label)
            st.write(label + "…")
            t0 = time.time()
            out = fn(*args)
            st.caption(f"   ↳ done in {time.time() - t0:.1f}s")
            return out

        chunks = step(0, steps[0][0], process_input, source)
        transcript = step(1, steps[1][0], transcribe_all, chunks, language)
        cleanup_temp_files(chunks)
        result["transcript"] = transcript
        result["title"] = step(2, steps[2][0], generate_title, transcript)
        result["summary"] = step(3, steps[3][0], summarize, transcript)
        result["action_items"] = step(4, steps[4][0], extract_action_items, transcript)
        result["key_decisions"] = step(5, steps[5][0], extract_key_decisions, transcript)
        result["open_questions"] = step(6, steps[6][0], extract_questions, transcript)
        result["rag_chain"] = step(7, steps[7][0], build_rag_chain, transcript)

        progress.progress(1.0, text="Done ✅")
        status.update(label="Processing complete ✅", state="complete", expanded=False)

    return result


